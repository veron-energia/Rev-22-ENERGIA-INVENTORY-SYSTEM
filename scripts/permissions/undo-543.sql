    from pg_proc p where p.pronamespace = 'public'::regnamespace and p.prokind = 'f';

  -- 2. Put back
  foreach g in array c_grants loop
    execute format('grant %s on table public.%I to %I', split_part(g, ':', 3), split_part(g, ':', 1), split_part(g, ':', 2));
  end loop;
  alter default privileges for role postgres in schema public grant truncate, references, trigger on tables to anon, authenticated;

  -- 3. Checks after
  select md5(string_agg(c.relname || '=' || coalesce((select string_agg(a::text, ',' order by a::text) from unnest(c.relacl) a), '')
                        || '/' || c.relrowsecurity, '|' order by c.relname)) into v_acl
    from pg_class c where c.relnamespace = 'public'::regnamespace and c.relkind in ('r', 'v', 'm', 'S', 'p', 'f');
  select d.defaclacl::text into v_def from pg_default_acl d
   where d.defaclrole = 'postgres'::regrole and d.defaclnamespace = 'public'::regnamespace and d.defaclobjtype = 'r';
  if v_acl is distinct from c_acl_before or v_def is distinct from c_def_before then
    raise exception 'undo 543: the grants are not as before 543 after putting them back (acl %, default %)', v_acl, v_def; end if;
  if (select md5(string_agg(md5(pg_get_functiondef(p.oid)), '' order by p.oid::regprocedure::text)) || '/' || count(*)
        from pg_proc p where p.pronamespace = 'public'::regnamespace and p.prokind = 'f') is distinct from v_fp then
    raise exception 'undo 543: a function changed'; end if;

  perform set_config('lock_timeout', v_lock, true);
  perform pg_notify('pgrst', 'reload schema');
end $undo$;
