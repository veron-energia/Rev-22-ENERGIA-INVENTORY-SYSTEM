-- 546_owner_rights_functions_search_temp_last.sql
--
-- EVERY OWNER-RIGHTS FUNCTION OF THE APP SEARCHES THE SESSION'S TEMPORARY SCHEMA LAST
--
--   From the security audit of 17 Nov 2026 (Low finding L15, its second half): the 1,019 the user
--   chose ("Change all 1,019", on the audit's count), plus 3 production-only functions of the same
--   kind (credit_package_price_for, report_uncorrectable_invoices, set_invoice_service_staff: made on
--   production outside the tracked migrations; only postgres and service_role may call them). MADE BY plan-backup/security-fixes-2026-11-17/l15-543-546/generate.py from a local
--   copy equal to production; rebuild it the same way if production changes (545 first). The pins
--   below are that copy's: the function fingerprint efa51a413557baeb605826fd7d777214/1462 before
--   and f5f09a8bf80f379ccdf38b6edaad0dbc/1462 after. If production differs when this is applied, it
--   refuses and changes nothing.
--   (The number 546 is this file's name and its errors' prefix; if it changes at commit, change it
--   in generate.py and build again.)
--
-- GO-LIVE: after 545, built again with generate.py once 545 is in. 545 changes credit_lot_policy,
--   which is not one of these (it runs with its caller's rights and has no settings), but it
--   changes the function fingerprint pinned here, so this refuses until it is rebuilt. Neither 545
--   nor scripts/credit-policy/undo-545.sql pins anything this changes. No page or Edge Function
--   changes. Every UNDO or one-off script written before this that pins an md5 of a function
--   changed here refuses once this is in (on main: undo-544, undo-540, undo-539, undo-538 and the
--   older ones, scripts/therapy/undo-502.sql, the two 502 presale scripts and three repair
--   scripts): run scripts/permissions/undo-546.sql first.
--
-- WHAT WAS WRONG
--
--   An owner-rights (SECURITY DEFINER) function runs with its owner's rights, postgres here. With
--   search_path set to public alone, PostgreSQL still searches the caller's temporary schema
--   (pg_temp) FIRST for tables and views: a login could make a temporary table named as a table a
--   function reads unqualified, and the function would read the login's table with the owner's
--   rights. PostgreSQL's advice for such functions is pg_temp written last. 1022 functions had
--   search_path public alone (541 and 542 already gave theirs public, pg_temp).
--
-- WHAT THIS DOES
--
--   * ALTER FUNCTION ... SET search_path = public, pg_temp on each of the 1022: every owner-rights
--     function in public owned by postgres, not part of an extension, whose search_path setting
--     is exactly public (invoice_date_evidence(uuid) keeps its TimeZone setting beside it). The
--     list is made when it runs and must be exactly the one below (md5 485cd023767dc226f898766983008777).
--   * Nothing else: the bodies (prosrc), arguments, results, owners, grants, volatility and every
--     other setting are as they were; only the SET search_path line of each definition changes.
--
-- WHAT STAYS
--
--   * Functions running with the caller's rights (their search path is the caller's; their own
--     setting, where they have one, as it is), extension functions (btree_gist and pg_trgm in
--     public, owned by supabase_admin), and the functions that already had public, pg_temp.
--   * No app function makes a temporary object with owner rights; the one function that makes
--     temporary tables, ads_resolve_all_attendance() (402), runs with its caller's rights, sets no
--     search path and is not callable by anon or authenticated.
--
-- UNDO
--
--   scripts/permissions/undo-546.sql: sets exactly these 1022 back to search_path = public. It
--   looks only at them (each there with 546's search path, their bodies as 546 was made with), so a
--   later migration that changes other functions does not stop it. Run it BEFORE any older UNDO.
--
-- NO SELF-TEST INSIDE; the suite is scripts/permissions/tests/search-path-546.sql.
--
-- One transaction with its history row, by the usual wrapper; nothing else is written.

